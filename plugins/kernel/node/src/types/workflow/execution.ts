/**
 * The plugin-facing facade for node execution. This is the ONLY interface plugins may
 * use to invoke tools/models, emit artifacts, observe time, or log. Provided by the engine.
 */
export type NodeExecutionContext = {
  /** Run-scoped logger; all lines carry runId + node. */
  logger: LoggerService;
  /** The only path to tools from within this specific vertex execution loop. */
  tools: ToolExecutor;
  /** The only path to models from within this specific vertex execution loop. */
  model: ModelExecutor;
  /** Emit a typed artifact event + persist. Kind must be declared on the workflow. */
  emitArtifact(kind: string, payload: { ref?: string; url?: string }): Promise<void>;
  /** Deterministic clock (injectable; defaults to Date). Tests freeze it. */
  now(): Date;
  /** Abort signal honoring run cancellation and per-node timeouts. */
  signal: AbortSignal;
};

/**
 * ============================================================================
 *   STEP EXECUTOR EXECUTABLE PRIMITIVES
 * ============================================================================
 */

/**
 * The only path to tools from within a workflow node. Enforces allow-lists, provider
 * policy, RBAC filtering, effect gating, budgets, and audit. Provided by the engine.
 */
export type ToolExecutor = {
  invoke<TArgs = unknown, TResult = unknown>(input: {
    toolId: string;
    args: TArgs;
    limits?: ToolInvocationLimits;
  }): Promise<ToolInvocationResult<TResult>>;
  /**
   * Scatter-gather over all providers allowed for this call. Opt-in per category;
   * a category must declare `supportsScatterGather`. Per-provider failures captured.
   */
  invokeAll?<TArgs = unknown, TResult = unknown>(input: {
    toolId: string;
    args: TArgs;
    limits?: ToolInvocationLimits;
  }): Promise<ToolInvocationResult<TResult>[]>;
};

/**
 * The only path to models from within a workflow node. Streams tokens as events and
 * enforces token budgets. Provider-neutral; resolved from the agent's modelRef or a tier.
 */
export type ModelExecutor = {
  stream(input: { messages: ChatMessage[]; tools?: ToolSpec[] }): AsyncIterable<ModelChunk>;
  invoke(input: { messages: ChatMessage[] }): Promise<string>;
  /** Returns an executor bound to a named tier (`fast` / `reasoning` / ...). */
  forTier(tier: string): ModelExecutor;
};

/**
 * A chat-model message in `ModelExecutor` requests.
 */
export type ChatMessage = { role: 'system' | 'user' | 'assistant'; content: string };

/** A JSON-schema tool spec passed to models that support tool-calling. */
export type ToolSpec = {
  name: string;
  description?: string;
  schema?: unknown;
};

/**
 * A single streamed chunk emitted by a model execution step.
 */
export type ModelChunk = {
  text?: string;
  toolCalls?: { id: string; name: string; args: unknown }[];
  usage?: { input: number; output: number; total: number };
};

/**
 * ============================================================================
 *   HARDENING
 * ============================================================================
 */

/**
 * Security and resiliency configuration policies enforcing execution guardrails
 * within highly regulated enterprise multi-agent environments. These parameters
 * mitigate financial risk, loop conditions, and denial-of-service vector scenarios
 * by establishing deterministic compute limits.
 */
export interface HardeningOptions {
  /**
   * The absolute maximum time duration allowed for an entire workflow run execution
   * before forced termination. Prevents dangling agent runtime instances from consuming
   * infinite platform worker threads.
   */
  readonly timeoutMs?: number;

  /**
   * The total number of permitted retry actions executed by an agent step when a
   * recoverable fault occurs.
   */
  readonly maxRetries?: number;

  /**
   * The starting base time configuration used by automated exponential backoff algorithms
   * between retry attempts.
   */
  readonly retryBackoffMs?: number;

  /**
   * The cryptographic threshold defining the total text token capacity consumable during
   * a single workflow run execution. Serves as an essential protection barrier against
   * data exfiltration loops and high unexpected inference bills.
   */
  readonly maxTotalTokens?: number;

  /**
   * The absolute maximum runtime threshold allowed for any individual step or execution
   * block in isolation.
   */
  readonly maxNodeDurationMs?: number;

  /**
   * The strict maximum frequency threshold restricting request calls allowed down to
   * third-party endpoints within a one-minute window.
   */
  readonly rateLimitPerMinute?: number;
}
